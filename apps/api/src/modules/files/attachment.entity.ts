import { Column, Entity, Index } from 'typeorm';
import { AppBaseEntity } from '../../common/entities/base.entity';

/**
 * A file attached to any record (polymorphic owner). Versioned: uploading to
 * the same owner, category and file name adds a new version; earlier versions
 * stay downloadable. Files live in object storage under `storageKey`; the row
 * keeps the SHA-256, MIME type, size and uploader.
 */
@Entity('attachment')
@Index(['ownerType', 'ownerId'])
@Index(['ownerType', 'ownerId', 'category', 'fileName', 'version'], { unique: true })
export class Attachment extends AppBaseEntity {
  @Column({ type: 'varchar', length: 40 })
  ownerType: string;

  @Column({ type: 'uuid' })
  ownerId: string;

  /** e.g. DELIVERY_NOTE, CERTIFICATE, BID_DOCUMENT, LICENCE, PHOTO. */
  @Column({ type: 'varchar', length: 40 })
  category: string;

  @Column({ type: 'varchar', length: 255 })
  fileName: string;

  @Column({ type: 'varchar', length: 150 })
  mimeType: string;

  @Column({ type: 'bigint', transformer: { to: (v: number) => v, from: (v: string) => Number(v) } })
  sizeBytes: number;

  @Column({ type: 'char', length: 64 })
  sha256: string;

  @Column({ type: 'varchar', length: 400, unique: true })
  storageKey: string;

  @Column({ type: 'int' })
  version: number;

  /** The latest version of this owner / category / file name. */
  @Column({ type: 'boolean', default: true })
  isCurrent: boolean;

  @Column({ type: 'uuid', nullable: true })
  uploadedBy: string | null;

  /** True when generated by the system (e.g. a certificate PDF). */
  @Column({ type: 'boolean', default: false })
  generated: boolean;

  @Column({ type: 'varchar', length: 500, nullable: true })
  notes: string | null;
}
